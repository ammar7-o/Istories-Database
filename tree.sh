#!/usr/bin/env bash
# Rebuild the file tree used by index.html.
# Usage: ./tree.sh
set -euo pipefail

cd "$(dirname "$0")"

SITE_BASE_URL="${SITE_BASE_URL:-https://ammar7-o.github.io/Istories-Database/}"
export SITE_BASE_URL

python3 - <<'PY'
from __future__ import annotations

import json
import os
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path.cwd()
OUT = ROOT / "core" / "files.js"
BASE_URL = os.environ.get(
    "SITE_BASE_URL", "https://ammar7-o.github.io/Istories-Database/"
).strip()
if not BASE_URL.endswith("/"):
    BASE_URL += "/"

# These are app/build files, not part of the browsable database.
HIDDEN_TOP_LEVEL = {"core", "converter", "README.md", "index.html", "tree.sh"}
HIDDEN_ANYWHERE = {".git", ".idea", ".vscode", "__pycache__", "node_modules"}
HIDDEN_FILES = {".DS_Store", "Thumbs.db"}


def is_visible(rel: Path) -> bool:
    if any(part in HIDDEN_ANYWHERE for part in rel.parts):
        return False
    if rel.parts and rel.parts[0] in HIDDEN_TOP_LEVEL:
        return False
    if rel.name in HIDDEN_FILES:
        return False
    return True


def mtime(path: Path) -> str:
    return datetime.fromtimestamp(path.stat().st_mtime, timezone.utc).isoformat(
        timespec="seconds"
    )


folders: list[dict] = []
files: list[dict] = []

for path in sorted(ROOT.rglob("*"), key=lambda p: p.as_posix().lower()):
    rel = path.relative_to(ROOT)
    if not is_visible(rel):
        continue

    try:
        stat = path.stat()
    except OSError:
        continue

    if path.is_dir():
        folders.append(
            {
                "path": rel.as_posix(),
                "name": path.name,
                "mtime": mtime(path),
            }
        )
    elif path.is_file():
        files.append(
            {
                "path": rel.as_posix(),
                "name": path.name,
                "ext": path.suffix.lower().lstrip("."),
                "size": stat.st_size,
                "mtime": mtime(path),
            }
        )

payload = {
    "generatedAt": datetime.now(timezone.utc).isoformat(timespec="seconds"),
    "rootName": ROOT.name,
    "baseUrl": BASE_URL,
    "folders": folders,
    "files": files,
}

body = json.dumps(payload, ensure_ascii=False, indent=2)
body = body.replace("\u2028", "\\u2028").replace("\u2029", "\\u2029")

OUT.write_text(
    "// Auto-generated by tree.sh - do not edit by hand.\n"
    "// Regenerate with: ./tree.sh\n"
    f"window.ISTORIES_FILES = {body};\n",
    encoding="utf-8",
)

print(f"Wrote {len(files)} files and {len(folders)} folders to core/files.js")
PY
